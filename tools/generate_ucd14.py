"""Freeze Unicode 14.0.0 grapheme-break properties into a runtime module.

The UCD text files under data/unicode14 are treated as untrusted external
data: they are only parsed by this generator, never imported at runtime.
Run with: python3 -I tools/generate_ucd14.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data" / "unicode14"
OUT = ROOT / "src" / "taxonforge" / "_ucd14_data.py"
UNIDATA_VERSION = "14.0.0"


def parse_property(path, field_index=1):
    entries = []
    with open(path, encoding="utf-8") as stream:
        for line in stream:
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            codepoints, _, rest = line.partition(";")
            value = rest.split(";", 1)[0].split()[field_index - 1]
            if ".." in codepoints:
                start_s, end_s = codepoints.strip().split("..")
                start, end = int(start_s, 16), int(end_s, 16)
            else:
                start = end = int(codepoints.strip(), 16)
            entries.append((start, end, value))
    entries.sort()
    return entries


def coalesce(entries):
    merged = []
    for start, end, value in entries:
        if merged and start == merged[-1][1] + 1 and value == merged[-1][2]:
            merged[-1] = (merged[-1][0], end, value)
        else:
            merged.append((start, end, value))
    return merged


gcb = coalesce(parse_property(DATA / "GraphemeBreakProperty.txt"))
ep_raw = parse_property(DATA / "emoji-data.txt")
ep = coalesce([(s, e, "Extended_Pictographic") for s, e, v in ep_raw if v == "Extended_Pictographic"])

values = sorted({v for _, _, v in gcb})
value_index = {v: i for i, v in enumerate(values)}
gcb_ranges = [(s, e, value_index[v]) for s, e, v in gcb]
ep_ranges = [(s, e) for s, e, _ in ep]

# Sanity: no overlapping ranges within one table.
for table in (gcb_ranges, ep_ranges):
    for (s1, e1, *_), (s2, e2, *_) in zip(table, table[1:]):
        assert e1 < s2, (hex(e1), hex(s2))

content = f'''"""Frozen Unicode {UNIDATA_VERSION} grapheme-break property tables.

Generated by tools/generate_ucd14.py from the official UCD text files.
Do not edit by hand. Runtime code never reads the UCD text files.
"""

UNIDATA_VERSION = {UNIDATA_VERSION!r}
GCB_VALUES = {json.dumps(values)}
_GCB_RANGES = {json.dumps(gcb_ranges)}
_EP_RANGES = {json.dumps(ep_ranges)}
'''
OUT.write_text(content, encoding="utf-8")
print(f"wrote {OUT.relative_to(ROOT)}: {len(gcb_ranges)} GCB ranges, {len(ep_ranges)} EP ranges")
print("GCB values:", values)
